"""Deterministic independent big-integer oracle; does not call Fe implementation."""
import json
from pathlib import Path
from random import Random

ROOT = Path(__file__).resolve().parents[1]
MAX = (1 << 128) - 1
rng = Random(20261103)
triples = [(0, 0, 0), (0, MAX, 1), (MAX, MAX, MAX),
           (MAX, MAX, 1), (MAX - 1, MAX - 1, MAX - 2),
           (5, 1, 2), (7, 1, 2), (1, 1, 3), (2, 1, 3)]
for _ in range(120):
    triples.append((rng.randrange(MAX + 1), rng.randrange(MAX + 1),
                    rng.choice([0, 1, 2, 1000, 1000000, rng.randrange(1, MAX + 1)])))

vectors = []
for a, b, d in triples:
    for mode in ("Exact", "Floor", "Ceiling", "NearestEven"):
        if d == 0:
            expected = {"error": "DivisionByZero"}
        else:
            q, r = divmod(a * b, d)
            if mode == "Exact" and r:
                expected = {"error": "Inexact"}
            else:
                # Python's arbitrary precision is independent of Fe's u256 bound.
                if mode == "Ceiling" and r:
                    q += 1
                elif mode == "NearestEven" and (2 * r > d or (2 * r == d and q % 2)):
                    q += 1
                expected = {"error": "Overflow"} if q > MAX else {"value": str(q)}
        vectors.append({"a": str(a), "b": str(b), "denominator": str(d),
                        "rounding": mode, **expected})

lines = ["// Generated by tools/generate_vectors.py; independent exact-integer oracle.",
         "use ingot::{mul_div, ArithmeticError, Rounding}"]
for start in range(0, len(vectors), 24):
    lines += ["", "#[test]", f"fn oracle_batch_{start // 24:03d}() {{"]
    for v in vectors[start:start + 24]:
        call = (f"mul_div(a: {v['a']}, b: {v['b']}, denominator: {v['denominator']}, "
                f"rounding: Rounding::{v['rounding']})")
        if "error" in v:
            branch = f"Err(ArithmeticError::{v['error']}) => {{}}"
        else:
            branch = f"Ok(raw) => assert!(raw == {v['value']})"
        lines += [f"    match {call} {{", f"        {branch}",
                  "        _ => assert!(false)", "    }"]
    lines.append("}")
(ROOT / "src/oracle_tests.fe").write_text("\n".join(lines) + "\n", encoding="utf-8")
(ROOT / "oracle-vectors.json").write_text(json.dumps(vectors, indent=2) + "\n", encoding="utf-8")
print(json.dumps({"vectors": len(vectors), "seed": 20261103}))
